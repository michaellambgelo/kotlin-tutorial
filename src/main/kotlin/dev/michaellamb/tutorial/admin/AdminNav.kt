/*
 * The navigation bar shared by every app on admin.michaellamb.dev: GET /_nav/nav.js defines an
 * `<admin-nav>` custom element, and each app (these pages, and embed-admin on node2 at /embed/)
 * includes the script plus the element. Links come from [hubLinks], so the hub page and the bar
 * can't drift apart; LAN-only tools stay on the hub.
 *
 * Served only on the admin host, behind the same Access check as the hub. `/_nav` is a reserved
 * prefix there: no tunnel path rule may claim it (see the admin.michaellamb.dev coordination repo).
 * If the script fails to load, `<admin-nav>` stays an unknown, empty element and the app is unaffected.
 * Colours follow prefers-color-scheme; an app with a fixed palette sets `--admin-nav-bg`, `-fg`, `-line` and
 * `-accent` on the element (custom properties inherit into the shadow root).
 *
 * Kotlin note: the script is a raw string with `$`-free JS so no template escaping is needed; the one
 * substitution is a JSON literal written by Jackson, which also takes care of quoting the labels.
 */
package dev.michaellamb.tutorial.admin

import com.fasterxml.jackson.module.kotlin.jacksonObjectMapper
import io.ktor.http.ContentType
import io.ktor.server.response.respondText
import io.ktor.server.routing.Route
import io.ktor.server.routing.get
import kotlinx.html.BODY
import kotlinx.html.HEAD
import kotlinx.html.script
import kotlinx.html.style
import kotlinx.html.unsafe

const val NAV_SCRIPT_PATH = "/_nav/nav.js"

data class NavLink(val label: String, val href: String)

/** Hub first (it doesn't list itself), then every tool served on the admin host. */
fun navLinks(): List<NavLink> =
    listOf(NavLink("Hub", "/")) +
        hubLinks(AdminPaths.PORTAL).filter { !it.lanOnly }.map { NavLink(it.navLabel ?: it.label, it.href) }

private val mapper = jacksonObjectMapper()

fun navScript(links: List<NavLink> = navLinks()): String =
    NAV_JS_TEMPLATE.replace("__LINKS__", mapper.writeValueAsString(links))

fun Route.adminNavRoutes() {
    get(NAV_SCRIPT_PATH) {
        call.respondText(navScript(), ContentType.Application.JavaScript)
    }
}

fun HEAD.adminNavScript() {
    script(src = NAV_SCRIPT_PATH) { attributes["defer"] = "defer" }
    // Pull the bar flush to the edges of these pages' padded body (2rem 1rem).
    style { unsafe { +"admin-nav { display: block; margin: -2rem -1rem 1.5rem; }" } }
}

fun BODY.adminNavBar() {
    unsafe { +"<admin-nav></admin-nav>" }
}

private val NAV_JS_TEMPLATE = """
// <admin-nav>: the shared bar on admin.michaellamb.dev. Generated by kotlin-tutorial (admin/AdminNav.kt).
(() => {
  if (!window.customElements || customElements.get('admin-nav')) return;
  const LINKS = __LINKS__;
  const CSS = `
    :host { display: block; }
    nav { display: flex; gap: 0.25rem; overflow-x: auto; white-space: nowrap; padding: 0 0.75rem;
          border-bottom: 1px solid var(--line); background: var(--bg); color: var(--fg);
          font: 500 0.9rem/1 -apple-system, BlinkMacSystemFont, "Inter", system-ui, sans-serif;
          -webkit-overflow-scrolling: touch; scrollbar-width: none;
          --d-bg: #ffffff; --d-fg: #1a1a1a; --d-line: rgba(127,127,127,0.3); --d-accent: #1d6fe0;
          --bg: var(--admin-nav-bg, var(--d-bg)); --fg: var(--admin-nav-fg, var(--d-fg));
          --line: var(--admin-nav-line, var(--d-line)); --accent: var(--admin-nav-accent, var(--d-accent)); }
    nav::-webkit-scrollbar { display: none; }
    a { flex: none; color: inherit; text-decoration: none; padding: 0.85rem 0.6rem 0.7rem; opacity: 0.7;
        border-bottom: 2px solid transparent; }
    a:hover { opacity: 1; }
    a:focus-visible { outline: 2px solid var(--accent); outline-offset: -2px; }
    a[aria-current="page"] { opacity: 1; font-weight: 650; border-bottom-color: var(--accent); }
    @media (prefers-color-scheme: dark) {
      nav { --d-bg: #161616; --d-fg: #ececec; --d-line: rgba(160,160,160,0.25); --d-accent: #5b9bff; }
    }`;

  // Longest href that prefixes the path; "/" only matches itself.
  function current(path) {
    let best = null;
    for (const link of LINKS) {
      const h = link.href;
      const base = h.endsWith('/') ? h : h + '/';
      const hit = h === '/' ? path === '/' : (path === h || path === base.slice(0, -1) || path.startsWith(base));
      if (hit && (!best || h.length > best.href.length)) best = link;
    }
    return best;
  }

  class AdminNav extends HTMLElement {
    connectedCallback() {
      if (this.shadowRoot) return;
      const root = this.attachShadow({ mode: 'open' });
      const style = document.createElement('style');
      style.textContent = CSS;
      const nav = document.createElement('nav');
      nav.setAttribute('aria-label', 'Admin tools');
      const active = current(location.pathname);
      for (const link of LINKS) {
        const a = document.createElement('a');
        a.href = link.href;
        a.textContent = link.label;
        if (link === active) a.setAttribute('aria-current', 'page');
        nav.appendChild(a);
      }
      root.append(style, nav);
    }
  }
  customElements.define('admin-nav', AdminNav);
})();
""".trimStart()
